'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { starteBrowser, SPIELDATEI } = require('./lib/umgebung');
const { install, buildBundle, START, END } = require('../scripts/install-i18n.cjs');
const source = fs.readFileSync(SPIELDATEI, 'utf8');
let count = 0;
function check(name, actual, expected = true) { assert.deepEqual(actual, expected, name); count++; console.log('OK - ' + name); }
(async () => {
  check('Bundle is integrated in the actual game', source.includes(START) && source.includes(END));
  check('Build is deterministic and up to date', install(source), source);
  const stripped = source.slice(0, source.indexOf(START)) + source.slice(source.indexOf(END) + END.length).replace(/^\n/, '');
  check('Installing then removing bundle preserves original game bytes', install(stripped), source);
  assert.throws(() => install('not the game'), /bootstrap/); count++;
  assert.throws(() => install(source.replace(END, 'BROKEN_MARKER')), /markers/); count++;
  const bundle = buildBundle();
  check('Catalog cannot close the enclosing script', !/<\/script/i.test(bundle));
  check('Literal dollar patterns survive embedding', source.includes("return part.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&')"));
  const temp = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'kepler-i18n-'));
  const browser = await starteBrowser();
  try {
    // Real static markup and bundle, isolated from the unrelated game IIFE.
    const html = source.slice(0, source.indexOf('<script>')) + '<script>' + bundle + '</script></body></html>';
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const fixtureFile = path.join(temp, 'fixture.html'); fs.writeFileSync(fixtureFile, html);
    await page.route(/^https?:/, r => r.abort());
    await page.goto(require('node:url').pathToFileURL(fixtureFile).href);
    check('German is the default, independent of browser locale', await page.evaluate(() => KeplerI18n.language), 'de');
    await page.evaluate(() => { document.getElementById('loginOverlay').style.display='block'; });
    check('Language selector exists before login', await page.locator('#keplerLanguageLogin').isVisible());
    await page.selectOption('#keplerLanguageLogin', 'en');
    check('Language is stored outside the save', await page.evaluate(() => localStorage.getItem('kepler7_ui_language')), 'en');
    check('Document language follows selection', await page.getAttribute('html','lang'), 'en');
    check('Main navigation is English', (await page.locator('[data-tab="forschung"]').first().textContent()).trim(), 'Research');
    check('Header action is translated', await page.locator('#headerHelpBtn .header-btn-label').textContent(), 'Help');
    await page.reload();
    await page.evaluate(() => { document.getElementById('loginOverlay').style.display='block'; });
    check('Stored locale survives reload', await page.evaluate(() => KeplerI18n.language), 'en');
    check('At least 800 explicit translations', await page.evaluate(() => KeplerI18n.diagnostics().catalogEntries >= 800));
    check('Numeric interpolation preserves formatting', await page.evaluate(() => KeplerI18n.t('Stufe 1.234/5.678')), 'Level 1.234/5.678');
    check('No arbitrary name interpolation', await page.evaluate(() => KeplerI18n.t('Stufe Forschung')), 'Stufe Forschung');
    check('Unknown strings remain readable German', await page.evaluate(() => KeplerI18n.t('Ein unbekannter Text bleibt erhalten')), 'Ein unbekannter Text bleibt erhalten');
    check('Invalid locale cannot overwrite the setting', await page.evaluate(() => { const value=KeplerI18n.setLanguage('xx'); return value===false && KeplerI18n.language==='en'; }));
    await page.evaluate(() => {
      const root=document.getElementById('research');
      root.innerHTML='<button id="i18nTestButton" data-action="forschung" title="Erforschen">Erforschen</button><span id="i18nTestLabel">Stufe 12</span><span translate="no" id="i18nNoTranslate">Forschung</span><input id="i18nTestInput" value="Forschung" placeholder="Passwort"><select><option id="i18nPlayerOption">Forschung</option></select>';
      document.getElementById('chatPanelGlobalBox').innerHTML='<span id="i18nChat">Forschung</span>';
      const custom=document.createElement('span'); custom.className='dash-colony-name-text'; custom.id='i18nColony'; custom.textContent='Erz'; root.appendChild(custom);
      const outside=document.createElement('div'); outside.id='i18nUnknownRoot'; outside.textContent='Forschung'; document.body.appendChild(outside);
      window.__i18nClicks=0; document.getElementById('i18nTestButton').addEventListener('click',()=>window.__i18nClicks++);
    });
    await page.waitForTimeout(60);
    check('New dynamic button text translated', await page.locator('#i18nTestButton').textContent(), 'Research');
    check('Dynamic tooltip translated', await page.locator('#i18nTestButton').getAttribute('title'), 'Research');
    check('Action key is unchanged', await page.locator('#i18nTestButton').getAttribute('data-action'), 'forschung');
    check('Dynamic placeholder translated', await page.locator('#i18nTestInput').getAttribute('placeholder'), 'Password');
    check('Input values are never translated', await page.inputValue('#i18nTestInput'), 'Forschung');
    check('Player-named option is untouched', await page.locator('#i18nPlayerOption').textContent(), 'Forschung');
    check('Explicit exclusion is untouched', await page.locator('#i18nNoTranslate').textContent(), 'Forschung');
    check('Chat text is untouched', await page.locator('#i18nChat').textContent(), 'Forschung');
    check('Custom colony name is untouched', await page.locator('#i18nColony').textContent(), 'Erz');
    check('Unaudited dynamic roots are untouched', await page.locator('#i18nUnknownRoot').textContent(), 'Forschung');
    await page.evaluate(() => document.getElementById('i18nTestButton').click());
    check('Existing event handler remains attached', await page.evaluate(() => __i18nClicks), 1);
    await page.evaluate(() => { document.getElementById('i18nTestLabel').textContent='Stufe 24'; });
    await page.waitForTimeout(50);
    check('A later renderer update is translated', await page.locator('#i18nTestLabel').textContent(), 'Level 24');
    await page.evaluate(() => KeplerI18n.setLanguage('de'));
    check('Switching back restores latest text, not stale state', await page.locator('#i18nTestLabel').textContent(), 'Stufe 24');
    check('German button is restored', await page.locator('#i18nTestButton').textContent(), 'Erforschen');
    check('German tooltip is restored', await page.locator('#i18nTestButton').getAttribute('title'), 'Erforschen');
    const before = await page.evaluate(() => KeplerI18n.diagnostics().batches);
    await page.evaluate(() => document.getElementById('i18nTestLabel').textContent='Stufe 25');
    await page.waitForTimeout(70);
    check('No translation observer is running in German', await page.evaluate(() => KeplerI18n.diagnostics().batches), before);
    await page.evaluate(() => { localStorage.setItem('kepler7-save-v3','SAVE-SENTINEL'); localStorage.setItem('kepler7_token','SESSION-SENTINEL'); for(let i=0;i<10;i++){ KeplerI18n.setLanguage('en'); KeplerI18n.setLanguage('de'); } });
    check('Language switching does not alter saved progress or session', await page.evaluate(() => [localStorage.getItem('kepler7-save-v3'),localStorage.getItem('kepler7_token')]), ['SAVE-SENTINEL','SESSION-SENTINEL']);
    await page.evaluate(() => window.dispatchEvent(new StorageEvent('storage',{key:'kepler7_ui_language',newValue:'en'})));
    check('Language changes propagate across tabs', await page.evaluate(() => KeplerI18n.language), 'en');
    const settled = await page.evaluate(() => KeplerI18n.diagnostics().batches);
    await page.waitForTimeout(120);
    check('Observer does not loop on its own text updates', await page.evaluate(() => KeplerI18n.diagnostics().batches), settled);
    const selectBounds=await page.locator('#keplerLanguageLogin').boundingBox();
    check('Mobile selector has a 44px touch target', selectBounds && selectBounds.height>=44);
    check('Mobile selector fits the viewport', selectBounds && selectBounds.x>=0 && selectBounds.x+selectBounds.width<=390);
    await page.evaluate(() => { Storage.prototype.setItem=function(){throw new DOMException('blocked','SecurityError');}; KeplerI18n.setLanguage('de'); });
    check('Switching still works when storage is blocked', await page.evaluate(() => KeplerI18n.language), 'de');
    check('Storage failure is shown in settings', await page.locator('#keplerLanguageStorage').getAttribute('hidden'), null);
    check('No uncaught browser errors', errors, []);
    await context.close();
  } finally { await browser.close(); fs.rmSync(temp,{recursive:true,force:true}); }
  console.log('PASS: ' + count + ' language checks');
})().catch(error=>{console.error(error);process.exitCode=1;});
